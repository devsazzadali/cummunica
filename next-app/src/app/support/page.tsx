function fmtDate(iso: string): string {
  try { return new Date(iso).toLocaleString(); } catch { return iso; }
}

export default function SupportPage() {
  const [loggedIn, setLoggedIn] = useState(false);
  const [category, setCategory] = useState<SupportCategory>("login/account");
  const [subject, setSubject] = useState("");
  const [message, setMessage] = useState("");
  const [formError, setFormError] = useState("");
  const [formDone, setFormDone] = useState("");
  const [busy, setBusy] = useState(false);
  const [tickets, setTickets] = useState<Ticket[]>([]);
  const [listError, setListError] = useState("");
  const [listLoading, setListLoading] = useState(false);
  const [detail, setDetail] = useState<Ticket | null>(null);
  const [detailError, setDetailError] = useState("");

  const loadTickets = useCallback(async () => {
    setListLoading(true); setListError("");
    try {
      const d = await apiJson("/api/support") as { tickets: Ticket[] };
      setTickets(d.tickets);
    } catch (err) {
      setListError(err instanceof Error ? err.message : "tickets could not be loaded");
    }
    setListLoading(false);
  }, []);

  useEffect(() => {
    const hasToken = getToken() !== null;
    setLoggedIn(hasToken);
    if (hasToken) void loadTickets();
  }, [loadTickets]);

  const submit = async (e: React.FormEvent) => {
    e.preventDefault(); setFormError(""); setFormDone("");
    const s = subject.trim(); const m = message.trim();
    if (!SUPPORT_CATEGORIES.includes(category)) { setFormError("Please choose a category."); return; }
    if (s.length < MIN_TICKET_SUBJECT || s.length > MAX_TICKET_SUBJECT) { setFormError(`Subject must be ${MIN_TICKET_SUBJECT}–${MAX_TICKET_SUBJECT} characters.`); return; }
    if (m.length < MIN_TICKET_MESSAGE || m.length > MAX_TICKET_MESSAGE) { setFormError(`Please describe the problem in ${MIN_TICKET_MESSAGE}–${MAX_TICKET_MESSAGE} characters.`); return; }
    setBusy(true);
    try {
      const d = await apiJson("/api/support", { method: "POST", body: { category, subject: s, message: m } }) as { ticket: Ticket };
      setFormDone(`Ticket submitted: “${d.ticket.subject}”. You can follow it under My tickets below.`);
      setSubject(""); setMessage("");
      await loadTickets();
    } catch (err) {
      // Honest server error, never a fake success.
      setFormError(err instanceof Error ? err.message : "ticket was not submitted");
    }
    setBusy(false);
  };

  const openDetail = async (id: string) => {
    setDetailError(""); setDetail(null);
    try {
      const d = await apiJson(`/api/support/${id}`) as { ticket: Ticket };
      setDetail(d.ticket);
    } catch (err) {
      setDetailError(err instanceof Error ? err.message : "ticket could not be opened");
    }
  };

  return (
    <AppShell active="Settings">
      <header className="topbar topbar-page"><h1>Support</h1></header>
      <div className="wrap">
        <p className="support-intro"><LifeBuoy size={22} /> Get help with Communica, or report a problem. Start with the answers below — most questions are answered there.</p>

        <h2>Frequently asked questions</h2>
        <div className="support-faq">
          {FAQS.map((f) => (
            <details key={f.q}>
              <summary>{f.q}</summary>
              <p>{f.a}</p>
            </details>
          ))}
        </div>

        <h2><MessageSquareText size={20} style={{ verticalAlign: "middle" }} /> Report a problem</h2>
        {!loggedIn ? (
          <p className="demo-note" role="note">Tickets are for logged-in users, so support knows whose account to help. <Link href="/login">Login</Link> to submit a ticket — or read the answers above without logging in. No ticket is created until you log in and submit the form.</p>
        ) : (
          <form onSubmit={submit}>
            <label htmlFor="sup-category">Category</label>
            <select id="sup-category" value={category} onChange={(e) => setCategory(e.target.value as SupportCategory)}>
              {SUPPORT_CATEGORIES.map((c) => (<option key={c} value={c}>{SUPPORT_CATEGORY_LABELS[c]}</option>))}
            </select>
            <label htmlFor="sup-subject">Subject ({subject.length}/{MAX_TICKET_SUBJECT})</label>
            <input id="sup-subject" value={subject} onChange={(e) => setSubject(e.target.value)} placeholder="Short summary, e.g. Cannot log in with my Communica ID" maxLength={MAX_TICKET_SUBJECT} />
            <label htmlFor="sup-message">Describe the problem in detail ({message.length}/{MAX_TICKET_MESSAGE})</label>
            <textarea id="sup-message" value={message} onChange={(e) => setMessage(e.target.value)} placeholder="What happened, what you expected, and your @username if it is about your account. Never include your password." rows={6} maxLength={MAX_TICKET_MESSAGE} />
            <button className="btn btn-green btn-full" type="submit" disabled={busy}><Send size={18} />{busy ? "Submitting…" : "Submit ticket"}</button>
            {formError ? <p role="alert">{formError}</p> : null}
            {formDone ? <p role="status">{formDone}</p> : null}
            <p className="ai-label" style={{ textAlign: "left" }}>Support never asks for your password. Do not include passwords, OTP codes or bank details in a ticket.</p>
          </form>
        )}

        <h2>My tickets</h2>
        {!loggedIn ? (
          <p><Link className="btn btn-light btn-full" href="/login">Login to see your tickets</Link></p>
        ) : listLoading ? (
          <p>Loading your tickets…</p>
        ) : listError ? (
          <p role="alert">{listError}</p>
        ) : tickets.length === 0 ? (
          <p className="empty">You have no tickets yet. If something goes wrong, submit one above and it will appear here.</p>
        ) : (
          <div className="support-tickets">
            {tickets.map((t) => (
              <button key={t.id} type="button" className="support-ticket" onClick={() => void openDetail(t.id)}>
                <span className="support-ticket-main">
                  <strong>{t.subject}</strong>
                  <span className="support-ticket-meta">{SUPPORT_CATEGORY_LABELS[t.category as SupportCategory] ?? t.category} · {fmtDate(t.createdAt)}{t._count ? ` · ${t._count.replies} ${t._count.replies === 1 ? "reply" : "replies"}` : ""}</span>
                </span>
                <span className={`support-status support-status-${t.status}`}>{SUPPORT_STATUS_LABELS[t.status]}</span>
                <ChevronRight size={20} />
              </button>
            ))}
          </div>
        )}
        {detailError ? <p role="alert">{detailError}</p> : null}
        {detail ? (
          <section className="support-detail" aria-label="Ticket detail">
            <h3>{detail.subject}</h3>
            <p className="support-ticket-meta">{SUPPORT_CATEGORY_LABELS[detail.category as SupportCategory] ?? detail.category} · {SUPPORT_STATUS_LABELS[detail.status]} · {fmtDate(detail.createdAt)}</p>
            <p className="support-original">{detail.message}</p>
            <h3>Replies</h3>
            {!detail.replies || detail.replies.length === 0 ? (
              <p className="empty">No replies yet. Support will reply on this ticket when it is reviewed.</p>
            ) : (
              <div className="support-replies">
                {detail.replies.map((r) => (
                  <div key={r.id} className={r.isAdminReply ? "support-reply support-reply-admin" : "support-reply"}>
                    <p className="support-reply-head">{r.isAdminReply ? <><ShieldCheck size={16} /> Support</> : <><UserRound size={16} /> You</>} · {fmtDate(r.createdAt)}</p>
                    <p>{r.body}</p>
                  </div>
                ))}
              </div>
            )}
            <p className="ai-label" style={{ textAlign: "left" }}><Bot size={14} style={{ verticalAlign: "middle" }} /> SAZMU AI questions go in the SAZMU category above — this ticket thread is answered by support, not by the chatbot. <PhoneCall size={14} style={{ verticalAlign: "middle" }} /> Calls inside Communica are in-app only.</p>
          </section>
        ) : null}
      </div>
    </AppShell>
  );
}
